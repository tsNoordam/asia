"""Render docs/RESULTS_TABLES.md from results/eval/*.json, walk_forward.json
and robustness.json (run evaluate.py, walk_forward.py and robustness.py first).

Usage: python scripts/make_report.py
"""
import json
import pathlib

E = pathlib.Path("results/eval")
ORDER = ["B0_no_trade", "B1_simple_breakout", "B2_simple_fade", "B3_timed_long_00_11",
         "B4_eu_open_long_00_04", "B5_timed_long_02_16", "A_breakout_rep", "A_breakout_both",
         "C_hybrid_v1", "B_fade_v1", "B_fade_v1_long_only", "B_fade_v1_short_only", "B_fade_v2", "B_fade_v3"]
PERIODS = ["train", "val", "oos", "full"]


def f(x, kind="num"):
    if x is None or (isinstance(x, float) and x != x):
        return "–"
    if kind == "usd":
        return f"{x:,.0f}"
    if kind == "pct":
        return f"{100 * x:.1f}%"
    return f"{x:.2f}"


def row(name, per, s):
    if not s.get("trades"):
        return f"| {name} | {per} | 0 | 0 | – | – | – | – | – | – | – | 0 | 0.0% |"
    return (f"| {name} | {per} | {s['trades']} | {f(s['net_usd'], 'usd')} | {f(s['pf'])} | {f(s['win_rate'], 'pct')} | "
            f"{f(s['avg_usd'], 'usd')} | {f(s['avg_win'], 'usd')} | {f(s['avg_loss'], 'usd')} | {f(s['t_stat'])} | "
            f"{f(s['sharpe'])} | {f(s['max_dd_usd'], 'usd')} | {f(s['exposure'], 'pct')} |")


def main():
    rep = {n: json.loads((E / f"{n}.json").read_text()) for n in ORDER if (E / f"{n}.json").exists()}
    L = ["# Generated result tables", "",
         "Generated by `scripts/make_report.py`. Per contract, NQ ($20/pt), base costs ($5 round-turn commission + 1 tick "
         "slippage per side on market/stop fills, limit fills need 1 tick trade-through). USD figures. "
         "Sharpe = annualised mean/std of daily P&L over all eligible trading days (no-trade days = 0). "
         "TRAIN 2020-01-27..2022-12-31, VAL 2023-01-01..2024-06-30, OOS 2024-07-01..2026-10-23.", "",
         "## 1. Performance by period (base costs)", "",
         "| Strategy | Period | Trades | Net $ | PF | Win | Avg $ | Avg win $ | Avg loss $ | t | Sharpe | Max DD $ | Exposure |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for n, r in rep.items():
        for per in PERIODS:
            L.append(row(n, per, r["base"][per]))
    L += ["", "## 2. Long vs short (base costs)", "",
          "| Strategy | Side | Period | Trades | Net $ | Avg $ | t |", "|---|---|---|---|---|---|---|"]
    for n in ["A_breakout_both", "C_hybrid_v1", "B_fade_v1", "B_fade_v3"]:
        for side in ("long", "short"):
            for per in PERIODS[:3]:
                s = rep[n]["by_side"][side][per]
                L.append(f"| {n} | {side} | {per} | {s['trades']} | {f(s.get('net_usd', 0), 'usd')} | "
                         f"{f(s.get('avg_usd'), 'usd')} | {f(s.get('t_stat'))} |")
    L += ["", "## 3. By calendar year (base costs)", ""]
    for n in ["B1_simple_breakout", "B2_simple_fade", "A_breakout_both", "B_fade_v1", "B_fade_v3"]:
        L += [f"**{n}**", "", "| Year | Trades | Net $ | Avg $ | Win |", "|---|---|---|---|---|"]
        for y in rep[n]["by_year"]:
            L.append(f"| {y['day']} | {y['trades']} | {f(y['net_usd'], 'usd')} | {f(y['avg_usd'], 'usd')} | {f(y['win_rate'], 'pct')} |")
        L.append("")
    L += ["## 4. Cost sensitivity (average $ per trade / t-stat)", "",
          "gross = no costs; stress = $7 commission + 2 ticks per side; MNQ = $2/pt, $1.30 round turn, 1 tick.", "",
          "| Strategy | Costs | TRAIN avg / t | VAL avg / t | OOS avg / t |", "|---|---|---|---|---|"]
    for n in ["B1_simple_breakout", "A_breakout_both", "B_fade_v1", "B_fade_v3"]:
        for c in ("gross", "base", "stress", "mnq_base"):
            cells = [f"{f(rep[n][c][p]['avg_usd'], 'usd')} / {f(rep[n][c][p]['t_stat'])}" for p in ("train", "val", "oos")]
            L.append(f"| {n} | {c} | " + " | ".join(cells) + " |")
    L += ["", "## 5. One-at-a-time parameter sensitivity, final candidate B_fade_v3 (base costs)", "",
          "| Parameter | Value | TRAIN n / avg / t | VAL n / avg / t | OOS n / avg / t |", "|---|---|---|---|---|"]
    for s in rep["B_fade_v3"]["sensitivity"]:
        cells = [f"{s[p + '_trades']} / {f(s[p + '_avg_usd'], 'usd')} / {f(s[p + '_t_stat'])}" for p in ("train", "val", "oos")]
        L.append(f"| {s['param']} | {s['value']} | " + " | ".join(cells) + " |")
    L += ["", "Reference (v3 as frozen): " + " | ".join(
        f"{p.upper()} n={rep['B_fade_v3']['base'][p]['trades']} avg={f(rep['B_fade_v3']['base'][p]['avg_usd'], 'usd')} "
        f"t={f(rep['B_fade_v3']['base'][p]['t_stat'])}" for p in ("train", "val", "oos")), ""]
    L += ["Exit reasons (v3, all periods): " + ", ".join(f"{k}: {v}" for k, v in rep["B_fade_v3"]["exit_reasons"].items()), ""]

    wf = pathlib.Path("results/walk_forward.json")
    if wf.exists():
        w = json.loads(wf.read_text())
        L += ["## 6. Walk-forward (24-month trailing selection, 6-month test windows, 2022-01 → 2026-10)", "",
              "| Family | Trades | Net $ | Avg $ | PF | t | Sharpe | Max DD $ |", "|---|---|---|---|---|---|---|---|"]
        for fam, d in w.items():
            s = d["summary"]
            L.append(f"| {fam} | {s['trades']} | {f(s['net_usd'], 'usd')} | {f(s['avg_usd'], 'usd')} | {f(s['pf'])} | "
                     f"{f(s['t_stat'])} | {f(s['sharpe'])} | {f(s['max_dd_usd'], 'usd')} |")
        L += ["", "| Family | Test window | Chosen parameters | Trailing t | Test trades | Test net $ |", "|---|---|---|---|---|---|"]
        for fam, d in w.items():
            for x in d["windows"]:
                L.append(f"| {fam} | {x['test_start']} | {x['chosen']} | {x['train_t']} | {x['test_trades']} | {f(x['test_net_usd'], 'usd')} |")
        L.append("")

    rb = pathlib.Path("results/robustness.json")
    if rb.exists():
        r = json.loads(rb.read_text())
        L += ["## 7. Robustness", "",
              "| Check | Strategy | Trades | Avg $ | t | PF |", "|---|---|---|---|---|---|"]
        for n, d in r.items():
            for k in ("independent_data_tgt_2023_2025", "tos_same_days_2023_2025"):
                s = d[k]
                L.append(f"| {k} | {n} | {s['trades']} | {f(s['avg_usd'], 'usd')} | {f(s['t_stat'])} | {f(s['pf'])} |")
            for per, s in d["ES"].items():
                L.append(f"| /ES same rules ({per}, $50/pt) | {n} | {s['trades']} | {f(s['avg_usd'], 'usd')} | {f(s['t_stat'])} | {f(s['pf'])} |")
            for ses, dd in d["sessions"].items():
                for per, s in dd.items():
                    L.append(f"| Asian range {ses} ({per}) | {n} | {s['trades']} | {f(s['avg_usd'], 'usd')} | {f(s['t_stat'])} | {f(s['pf'])} |")
            for per, ci in d["bootstrap_mean_usd_ci95"].items():
                L.append(f"| Bootstrap 95% CI of mean trade ({per}) | {n} | – | [{f(ci[0], 'usd')}, {f(ci[1], 'usd')}] | – | – |")
        L.append("")
    pathlib.Path("docs/RESULTS_TABLES.md").write_text("\n".join(L))
    print("wrote docs/RESULTS_TABLES.md", len(L), "lines")


if __name__ == "__main__":
    main()
